#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// packaging/android/sync-android.mjs
// Synchronizes the built Android web bundle (dist/) and Capacitor configuration into the
// native Android Gradle project (android/), and verifies that no web PWA service worker
// or remote server URL was injected into the packaged APK assets.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '../..');
const DIST_DIR = path.join(ROOT_DIR, 'dist');
const ANDROID_DIR = path.join(ROOT_DIR, 'android');
const ANDROID_ASSETS_DIR = path.join(ANDROID_DIR, 'app/src/main/assets');
const ANDROID_PUBLIC_DIR = path.join(ANDROID_ASSETS_DIR, 'public');
const CAP_CONFIG_JSON_PATH = path.join(ROOT_DIR, 'capacitor.config.json');

const log = (message) => console.log(`[android:sync] ${message}`);
const fail = (message) => {
    console.error(`[android:sync] ERROR: ${message}`);
    process.exit(1);
};

if (!fs.existsSync(ANDROID_DIR)) {
    fail(`Android project directory not found at ${ANDROID_DIR}.`);
}

if (!fs.existsSync(CAP_CONFIG_JSON_PATH)) {
    fail(`Capacitor configuration file not found at ${CAP_CONFIG_JSON_PATH}.`);
}

const capConfig = JSON.parse(fs.readFileSync(CAP_CONFIG_JSON_PATH, 'utf8'));
if (capConfig?.server?.url) {
    fail(`capacitor.config.json must not define a remote server.url (${capConfig.server.url}); the APK must package local assets.`);
}

const distIndexHtmlPath = path.join(DIST_DIR, 'index.html');
if (!fs.existsSync(distIndexHtmlPath)) {
    fail(`Built web bundle not found at ${distIndexHtmlPath}. Run "npm run build:android:web" or "npm run build:android" first.`);
}

const distIndexHtml = fs.readFileSync(distIndexHtmlPath, 'utf8');
if (distIndexHtml.includes('registerSW.js') || fs.existsSync(path.join(DIST_DIR, 'registerSW.js')) || fs.existsSync(path.join(DIST_DIR, 'sw.js'))) {
    fail(
        'dist/ contains web PWA service worker artifacts (registerSW.js / sw.js). ' +
        'Build the Android web bundle with ANDROID=true ("npm run build:android:web") so the PWA service worker does not interfere with Capacitor native plugin injection.',
    );
}

// If @capacitor/cli is installed in node_modules, run `cap sync android` first so any newly added
// Capacitor plugins have their Gradle modules and plugin registry updated automatically.
const localCapBin = path.join(
    ROOT_DIR,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? 'cap.cmd' : 'cap',
);

if (fs.existsSync(localCapBin) && process.env.FOLIA_SKIP_CAP_CLI !== 'true') {
    log('Running local Capacitor CLI (cap sync android --inline)...');
    const result = spawnSync(localCapBin, ['sync', 'android'], {
        cwd: ROOT_DIR,
        stdio: 'inherit',
        shell: process.platform === 'win32',
    });
    if (result.status !== 0) {
        fail(`"cap sync android" exited with code ${result.status ?? 1}.`);
    }
}

// Always perform deterministic asset & config synchronization so the Android project is guaranteed
// to hold the exact dist/ files, capacitor.config.json, and Gradle Capacitor bindings.
fs.rmSync(ANDROID_PUBLIC_DIR, { recursive: true, force: true });
fs.mkdirSync(ANDROID_PUBLIC_DIR, { recursive: true });
fs.cpSync(DIST_DIR, ANDROID_PUBLIC_DIR, { recursive: true });

// Ensure runtime-config.js is present inside android/app/src/main/assets/public/
const publicRuntimeConfig = path.join(ROOT_DIR, 'public/runtime-config.js');
const targetRuntimeConfig = path.join(ANDROID_PUBLIC_DIR, 'runtime-config.js');
if (!fs.existsSync(targetRuntimeConfig) && fs.existsSync(publicRuntimeConfig)) {
    fs.copyFileSync(publicRuntimeConfig, targetRuntimeConfig);
}

fs.writeFileSync(
    path.join(ANDROID_ASSETS_DIR, 'capacitor.config.json'),
    `${JSON.stringify(capConfig, null, '\t')}\n`,
    'utf8',
);

const pluginsJsonPath = path.join(ANDROID_ASSETS_DIR, 'capacitor.plugins.json');
if (!fs.existsSync(pluginsJsonPath)) {
    fs.writeFileSync(pluginsJsonPath, '[]\n', 'utf8');
}

const capacitorSettingsGradlePath = path.join(ANDROID_DIR, 'capacitor.settings.gradle');
if (!fs.existsSync(capacitorSettingsGradlePath)) {
    fs.writeFileSync(
        capacitorSettingsGradlePath,
        [
            '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
            "include ':capacitor-android'",
            "project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')",
            '',
        ].join('\n'),
        'utf8',
    );
}

const syncedIndexPath = path.join(ANDROID_PUBLIC_DIR, 'index.html');
if (!fs.existsSync(syncedIndexPath)) {
    fail(`Failed to copy index.html to ${syncedIndexPath}.`);
}

log(`Synced web bundle from ${DIST_DIR} -> ${ANDROID_PUBLIC_DIR}`);
log(`Verified appId="${capConfig.appId}", appName="${capConfig.appName}", and service-worker-free index.html.`);
